<script>
/* Highlight the nav item of the CURRENT page (the template never set one,
   so "Dashboard" always looked selected via its hardcoded blue icon). */
(function () {
    var page = (location.pathname.split('/').pop() || 'dashboard').replace(/\.php$/, '') || 'dashboard';
    var alias = { data_table: 'history', 'view-profile': 'history', 'view-detail': 'history', usage_analytics: 'history', index: 'dashboard' };
    if (alias[page]) page = alias[page];
    document.querySelectorAll('.sidebar-nav .nav-item > a').forEach(function (a) {
        var target = (a.getAttribute('href') || '').replace('./', '').replace(/\.php$/, '');
        if (target === page) a.classList.add('active');
    });
})();
</script>







